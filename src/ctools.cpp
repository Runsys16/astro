char* deg2str_hms(double r, char* str, int len)
{
	struct hms 			HMS;
	
    if ( r<0.0 )	r = 360.0 + r;
    
    double h = (r / 360.0 * 24.0);
    int H = h;
    HMS.h = H;
    
    double m = (h-H) * 60.0;
    int M = m;
    HMS.m = M;
    
    double s = (m-M) * 60.0;
    HMS.s = s;
    
    int is = floor(s);
    int cs = floor( (s-(double)is)*100.0);

	snprintf( (char*)str, len, "%02.0lfh %02.0lfm %02d.%02ds", HMS.h, HMS.m, is, cs );

    return str;
}
