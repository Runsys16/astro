char* deg2str_dms(double d, char* str, int len)
{
 	struct dms 			DMS;
 	
    double sign = 1.0;

    if ( d<0.0 )
    {
        sign = -1.0;
        d *=-1.0;
    }

    int D = d;
    DMS.d = D;
    
    double m = (d-D) * 60.0;
    //if ( d < 0.0 )  m *= -1.0;
    int M = m;
    DMS.m = M;
    
    double s = (m-M) * 60.0;
    DMS.s = s;

    DMS.d *= sign;
    
    int is = (int)floor(s);
    int cs = (int)floor( (s-(double)is)*100.0);

	snprintf( (char*)str, len, "%02.0lf° %02.0lf' %02d.%02d\"", DMS.d, DMS.m, is, cs );
	return str;
}

