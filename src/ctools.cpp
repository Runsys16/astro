double hms2rad(struct hms& HMS)
{
    return (HMS.h + HMS.m/60.0 + HMS.s/3600.0) / 12.0*M_PI;
}
//--------------------------------------------------------------------------------------------------------------------
//
//--------------------------------------------------------------------------------------------------------------------
double dms2rad(struct dms& DMS)
{
	double signe = 1.0;
	if ( DMS.d < 0.0 )		signe = -1.0;		
    return signe*(abs(DMS.d) + DMS.m/60.0 + DMS.s/3600.0) / 180.0*M_PI;
}
