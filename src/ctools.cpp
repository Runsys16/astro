void rad2hms(double r, struct hms& HMS)
{
    double sign = 1.0;
    double hDouze = 0.0;
    if ( r<0.0 )
    {
        sign = -1.0;
        //r *=-1.0;
        hDouze = 24.0;
    }
    double h = hDouze + (r / M_PI * 12.0);
    int H = h;
    HMS.h = H;
    
    double m = (h-H) * 60.0;
    //if ( h < 0.0 )  m *= -1.0;
    int M = m;
    HMS.m = M;
    
    double s = (m-M) * 60.0;
    HMS.s = s;
    
    //HMS.h *= sign;
}
