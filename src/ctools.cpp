void rad2dms(double v, struct dms& DMS)
{
    double sign = 1.0;

    if ( v<0.0 )        sign = -1.0;

    double d = abs(v) / M_PI * 180.0;
    int D = d;
    DMS.d = D;
    
    double m = (d-D) * 60.0;
    //if ( d < 0.0 )  m *= -1.0;
    int M = m;
    DMS.m = M;
    
    double s = (m-M) * 60.0;
    DMS.s = s;

    DMS.d *= sign;
}
